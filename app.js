/** Recolours the drawn SVG in place. Each term carries data-tone, so the
    new colour is a lookup rather than a recomputation from the values. */
function recolorCloud() {
  const svg = cloud.querySelector('svg');
  if (!svg) return;
  const c = termColors();
  const bg = svg.querySelector('.cloud-bg');
  if (bg) bg.setAttribute('fill', c.paper);
  for (const t of svg.querySelectorAll('text')) {
    t.setAttribute('fill', c[t.dataset.tone] || c.mid);
  }
}

function setTheme(next, { remember = true } = {}) {
  document.documentElement.setAttribute('data-theme', next === 'dark' ? 'dark' : 'light');
  if (remember) {
    try { localStorage.setItem(THEME_KEY, next); } catch { /* private mode */ }
  }
  paintThemeToggle();
  recolorCloud();
}

/* ══════════════════════════════════════════════════════════════
   TERMS ADDED BY HAND
   Two sources, merged: data/manual-terms.js (committed, everyone
   sees it) and localStorage (this browser only, added on the page).
══════════════════════════════════════════════════════════════ */

/** "Term | 3" -> {text:'Term', value:3}. "# note" and blanks are skipped. */
function parseTerms(text) {
  if (!text) return [];
  return text.split('\n')
    .map(l => l.trim())
    .filter(l => l && !l.startsWith('#'))
    .map(l => {
      const [label, weight] = l.split('|');
      const t = label.trim();
      return t ? { text: t, value: Math.max(1, Math.round(Number(weight)) || 1) } : null;
    })
    .filter(Boolean);
}

function readStored() {
  try { return localStorage.getItem(STORAGE_KEY) || ''; } catch { return ''; }
}

function writeStored(text) {
  try {
    if (text.trim()) localStorage.setItem(STORAGE_KEY, text);
    else localStorage.removeItem(STORAGE_KEY);
    return true;
  } catch { return false; }
}

function addedTerms() {
  return mergeTerms(
    parseTerms(window.WORDCLOUD_MANUAL_TERMS || ''),
    parseTerms(readStored())
  );
}

/** Highest weight wins for duplicates. */
function mergeTerms(base, extra) {
  const seen = new Map();
  for (const t of [...base, ...extra]) {
    const key = t.text.toLowerCase();
    const hit = seen.get(key);
    if (hit) {
      hit.value = Math.max(hit.value, t.value);
      hit.added = hit.added && t.added;
    } else {
      seen.set(key, { ...t });
    }
  }
  return Array.from(seen.values());
}

/* ══ TEXT PROCESSING ═══════════════════════════════════════════ */

function stopSet() {
  return new Set(stopwords.value.split(',').map(w => w.trim().toLowerCase()).filter(Boolean));
}

/** Single-words view: word frequency across the corpus. */
function countWords(text) {
  const stops = stopSet();
  const freq = {};
  for (const t of text.toLowerCase().replace(/[^a-z\s]/g, ' ').split(/\s+/)) {
    if (t.length > 1 && !stops.has(t)) freq[t] = (freq[t] || 0) + 1;
  }
  return Object.entries(freq)
    .map(([text, value]) => ({ text, value }))
    .sort((a, b) => b.value - a.value);
}

/** Phrases view for free text: people separate terms with , ; . / or newlines. */
function countPhrases(text) {
  const seen = new Map();
  for (const part of text.split(/[,;.\n\/]+/)) {
    const phrase = part.trim().replace(/\s+/g, ' ').replace(/^[?!\s]+|[?!\s]+$/g, '');
    if (phrase.length < 2) continue;
    const key = phrase.toLowerCase();
    const hit = seen.get(key);
    if (hit) hit.value += 1;
    else seen.set(key, { text: phrase, value: 1 });
  }
  return Array.from(seen.values()).sort((a, b) => b.value - a.value);
}

/** Builds the term list for the current source and view. */
function buildTerms() {
  const preset = activePreset();
  const added  = addedTerms().map(t => ({ ...t, added: true }));

  if (viewMode !== 'words') {
    const base = preset
      ? preset.phrases.map(p => ({ ...p, added: false }))
      : countPhrases(textInput.value.trim()).map(p => ({ ...p, added: false }));
    return mergeTerms(base, added).sort((a, b) => b.value - a.value);
  }

  // Single words: fold the added terms into the corpus, repeated by weight,
  // so their size reflects the weight that was asked for.
  const corpus = preset ? preset.sourceText : textInput.value.trim();
  const addedCorpus = added.map(t => Array(t.value).fill(t.text).join(' ')).join(' ');

  // A word counts as added only if it appears nowhere in the survey corpus.
  const corpusWords = new Set(countWords(corpus).map(w => w.text));
  return countWords(`${corpus} ${addedCorpus}`)
    .map(w => ({ ...w, added: !corpusWords.has(w.text) }));
}

/* ══ RENDER ════════════════════════════════════════════════════ */

function sizeScale(terms, range) {
  if (!terms.length) return () => range.min;
  const hi = terms[0].value;
  const lo = terms[terms.length - 1].value;
  if (hi === lo) return () => Math.round((range.min + range.max) / 2);
  return v => Math.round(range.min + ((v - lo) / (hi - lo)) * (range.max - range.min));
}

/**
 * A long phrase at full size can be wider than the plate, and d3-cloud
 * silently drops whatever it cannot place. Cap each term to what fits so
 * no term goes missing.
 */
function fitWidth(size, text, width, floor) {
  const RATIO = 0.5; // condensed semibold, measured
  return Math.max(floor, Math.min(size, Math.floor((width * 0.94) / (RATIO * Math.max(text.length, 1)))));
}

/**
 * Which band a term falls in — 'hi', 'mid', 'lo' or 'added'. The band is
 * what gets stored on the element; the hex is looked up from the band, so
 * switching theme or exporting a PNG only changes the lookup table.
 */
function termTone(term, hi, lo) {
  if (term.added) return 'added';
  if (hi === lo) return 'mid';
  if (term.value === hi) return 'hi';
  return term.value > lo ? 'mid' : 'lo';
}

function render(terms) {
  if (layout) { layout.stop(); layout = null; }

  /* In the page the plate's height is derived from its width, which keeps
     the figure a fixed aspect however the window is sized. Full screen it
     is the screen, so the real measured height is used and the cloud fills
     the display edge to edge. */
  const full   = isFullscreen();
  const width  = plate.clientWidth || 1100;
  const height = full
    ? (plate.clientHeight || Math.max(Math.round(width * 0.46), 320))
    : Math.max(Math.round(width * 0.46), 320);
  const range  = fontRange(width, height, full ? MAX_UPSCALE : 1);
  const scale  = sizeScale(terms, range);
  const hi = terms[0].value;
  const lo = terms[terms.length - 1].value;

  const floor = Math.min(range.min, 13);

  const buildWords = (shrink) => terms.map(t => ({
    text:  t.text,
    value: t.value,
    added: !!t.added,
    size:  Math.max(floor, Math.round(fitWidth(scale(t.value), t.text, width, floor) * shrink)),
    tone:  termTone(t, hi, lo),
  }));

  /* d3-cloud drops any term it cannot place, and whether a term fits depends
     on how the ones before it happened to pack. Rather than tune the size
     constants until it works for this one dataset, shrink and try again until
     everything lands — which keeps working as terms are added. */
  const MIN_SHRINK = 0.5;
  let words = [];

  function attempt(shrink) {
    if (layout) { layout.stop(); layout = null; }
    words = buildWords(shrink);

    layout = d3.layout.cloud()
      .size([width, height])
      .words(words)
      .padding(7)
      .rotate(0)
      .font(CLOUD_FONT)
      .fontWeight(CLOUD_WEIGHT)
      .fontSize(d => d.size)
      .spiral('archimedean')
      .on('end', placed => {
        if (placed.length < words.length && shrink > MIN_SHRINK) {
          attempt(shrink * 0.9);
          return;
        }
        draw(placed);
      })
      .start();
  }

  attempt(1);

  function draw(placed) {
    cloud.innerHTML = '';
    const c = termColors();

    const svg = d3.select(cloud).append('svg')
      .attr('xmlns', 'http://www.w3.org/2000/svg')
      .attr('viewBox', `0 0 ${width} ${height}`)
      .attr('width', width)
      .attr('height', height);

    svg.append('rect')
      .attr('class', 'cloud-bg')
      .attr('width', width).attr('height', height)
      .attr('fill', c.paper);

    svg.append('g')
        .attr('class', 'cloud-stage')
        .attr('transform', `translate(${width / 2},${height / 2})`)
      .selectAll('text')
      .data(placed)
      .enter()
      .append('text')
        .attr('text-anchor', 'middle')
        .attr('font-family', CLOUD_FONT)
        .attr('font-weight', CLOUD_WEIGHT)
        .attr('font-size', d => `${d.size}px`)
        .attr('fill', d => c[d.tone] || c.mid)
        .attr('data-tone', d => d.tone)
        /* Resting position and size, kept so the PNG export can put every
           term back where it belongs. */
        .attr('data-bx', d => d.x)
        .attr('data-by', d => d.y)
        .attr('data-bs', d => d.size)
        .attr('transform', d => `translate(${d.x},${d.y})`)
        .text(d => d.text)
      .append('title')
        .text(d => d.added
          ? `${d.text} — added by hand`
          : `${d.text} — raised ${d.value} time${d.value !== 1 ? 's' : ''}`);

    cloud.style.display = 'block';
    plateEmpty.style.display = 'none';
    savePngBtn.disabled = false;

    // The notice belongs next to the cloud, not in the drawer — the drawer is
    // shut by the time anyone reads this.
    const missed = words.length - placed.length;
    if (missed > 0) {
      const names = words.filter(w => !placed.includes(w)).map(w => w.text).join(', ');
      say(fitNote, `${missed} term${missed !== 1 ? 's did' : ' did'} not fit: ${names}. Widen the window, or shorten the longest of them.`, 'warn');
    } else {
      hide(fitNote);
    }
  }
}

/** Recomputes and redraws from current state. */
function refresh({ announce = false } = {}) {
  const terms = buildTerms();

  if (!terms.length) {
    cloud.innerHTML = '';
    cloud.style.display = 'none';
    plateEmpty.style.display = 'block';
    savePngBtn.disabled = true;
    hide(fitNote);
    if (announce) {
      say(problem, viewMode === 'phrases'
        ? 'There is nothing to draw yet. Paste some text, drop in a file, or add a term by hand.'
        : 'Every word was filtered out. Remove some entries from "Words to ignore", or add more text.', 'bad');
    }
    updateCaption();
    return;
  }

  hide(problem);
  render(terms);
  updateCaption();
}

/* ══════════════════════════════════════════════════════════════
   FULL SCREEN

   One click puts the cloud on the whole screen with nothing else on it:
   the top bar, the caption and the buttons under the plate are all
   outside the element that goes full screen, so they simply are not
   there. The Fullscreen API is prefixed on older WebKit, hence the
   small shims.

   The cloud is laid out again rather than scaled up. Scaling a 1180px
   layout to 1920 would leave the same gaps and the same type
   relationships, just bigger and softer; re-running d3-cloud at the new
   size repacks the terms and re-quotes the type for the screen, which is
   the whole point of doing this on a projector.
══════════════════════════════════════════════════════════════ */

const fsElement = () =>
  document.fullscreenElement || document.webkitFullscreenElement || null;

const isFullscreen = () => fsElement() === plate;

function paintFsButton() {
  const on = isFullscreen();
  plate.classList.toggle('is-fs', on);
  fsBtn.setAttribute('aria-pressed', String(on));
  fsBtn.setAttribute('aria-label', on ? 'Leave full screen' : 'Show the cloud full screen');
  fsBtn.title = on ? 'Leave full screen (Esc)' : 'Full screen (F)';
}

function toggleFullscreen() {
  if (isFullscreen()) {
    const exit = document.exitFullscreen || document.webkitExitFullscreen;
    if (exit) exit.call(document);
    return;
  }

  const req = plate.requestFullscreen || plate.webkitRequestFullscreen;
  if (!req) {
    // Kiosk browsers and a few embeds refuse it. Say so rather than
    // leaving a button that does nothing when pressed.
    say(fitNote, 'This browser will not let the page go full screen. Use its own full-screen control instead — F11 on Windows.', 'warn');
    return;
  }

  // Firefox rejects rather than throws, so both paths need catching.
  try {
    const r = req.call(plate);
    if (r && typeof r.catch === 'function') r.catch(() => {});
  } catch { /* refused — paintFsButton never runs, so nothing to undo */ }
}

/* Entering and leaving both change the plate's size, so the cloud has to
   be laid out again either way. Deferred a frame because the browser
   reports the change before it has finished resizing the element, and
   reading clientWidth too early lays the cloud out for the old box. */
function onFullscreenChange() {
  paintFsButton();
  requestAnimationFrame(() => {
    requestAnimationFrame(() => {
      if (cloud.style.display !== 'none' && cloud.querySelector('svg')) refresh();
    });
  });
}

/* ══ CAPTION ═══════════════════════════════════════════════════ */

function updateCaption() {
  const preset = activePreset();
  const added  = addedTerms();

  legendAdded.hidden = added.length === 0;

  if (preset) {
    /* Named, not itemised. The room does not need the file name, the sheet
       and the extraction date under the figure; what it needs to know is
       that these are their own words, taken from the question they were
       asked. The full provenance stays in the repository README. */
    capSource.textContent = 'Source: Poll, "Keywords – what\'s on your mind?"';
  } else {
    const name = fileName.textContent.trim();
    capSource.textContent = name
      ? `Source: the file "${name}", read in this browser and not uploaded anywhere.`
      : 'Source: text typed or pasted into this page.';
  }
}

/* ══ SOURCE PICKER ═════════════════════════════════════════════ */

function initPresets() {
  presetSel.innerHTML = '';

  for (const p of PRESETS) {
    const o = document.createElement('option');
    o.value = p.id;
    o.textContent = p.label;
    presetSel.appendChild(o);
  }

  const custom = document.createElement('option');
  custom.value = CUSTOM;
  custom.textContent = 'My own text or file';
  presetSel.appendChild(custom);

  presetId = PRESETS.length ? PRESETS[0].id : null;
  presetSel.value = presetId || CUSTOM;
  updatePresetHint();
}

function updatePresetHint() {
  const p = activePreset();
  presetHint.textContent = p
    ? `${p.responseCount} answers, ${p.phrases.length} terms.`
    : 'Drawn from whatever you paste or upload below.';
}

function useCustom() {
  presetId = null;
  presetSel.value = CUSTOM;
  updatePresetHint();
}

/* ══ VIEW SWITCH ═══════════════════════════════════════════════ */

function paintSwitch() {
  for (const b of switchOpts) {
    const on = b.dataset.view === viewMode;
    b.classList.toggle('is-on', on);
    b.setAttribute('aria-selected', String(on));
  }
}

const VIEWS = ['phrases', 'words'];

function setView(mode, { redraw = true } = {}) {
  if (!VIEWS.includes(mode)) return;
  if (mode === viewMode && redraw) return;
  viewMode = mode;
  paintSwitch();

  // Keep the view in the URL so a link can point straight at either one.
  try {
    const url = new URL(location.href);
    url.searchParams.set('view', mode);
    history.replaceState(null, '', url);
  } catch { /* not worth failing the render over */ }

  if (redraw) refresh();
}

