/* ══ ACTIONS ═══════════════════════════════════════════════════ */

function handleGenerate() {
  const raw = textInput.value.trim();
  if (raw && presetId) useCustom();

  if (!raw && !presetId && !addedTerms().length) {
    say(problem, 'Paste some text, choose a file, or pick a source above first.', 'bad');
    return;
  }

  busy(true);
  // Lets the spinner paint before the synchronous layout run.
  setTimeout(() => {
    refresh({ announce: true });
    busy(false);
    if (problem.hidden) closeDrawer(); // nothing went wrong, so get out of the way
  }, 30);
}

function handleStartOver() {
  textInput.value = '';
  fileName.textContent = '';
  fileInput.value = '';
  hide(problem);
  presetId = PRESETS.length ? PRESETS[0].id : null;
  presetSel.value = presetId || CUSTOM;
  updatePresetHint();
  refresh();
}

/**
 * The export copy: light palette, white plate, every term back at its
 * resting position at full opacity. So a PNG is the same picture whether
 * it was taken in dark mode or light, and it drops straight onto a white
 * Elsevier slide.
 */
function exportSvg(svg) {
  const copy = svg.cloneNode(true);
  const c = PALETTE.light;

  const bg = copy.querySelector('.cloud-bg');
  if (bg) bg.setAttribute('fill', c.paper);

  const stage = copy.querySelector('.cloud-stage');
  if (stage) {
    const w = parseInt(copy.getAttribute('width'), 10) || 1100;
    const h = parseInt(copy.getAttribute('height'), 10) || 560;
    stage.setAttribute('transform', `translate(${w / 2},${h / 2})`);
  }

  for (const t of copy.querySelectorAll('text')) {
    t.setAttribute('fill', c[t.dataset.tone] || c.mid);
    t.setAttribute('opacity', '1');
    t.setAttribute('transform', `translate(${t.dataset.bx || 0},${t.dataset.by || 0})`);
  }

  return copy;
}

function handleSavePng() {
  const svg = cloud.querySelector('svg');
  if (!svg) return;

  const w = parseInt(svg.getAttribute('width'), 10) || 1100;
  const h = parseInt(svg.getAttribute('height'), 10) || 560;
  const k = 2; // 2x, so it holds up in a deck or in print

  const canvas = document.createElement('canvas');
  canvas.width = w * k;
  canvas.height = h * k;

  const ctx = canvas.getContext('2d');
  ctx.scale(k, k);
  ctx.fillStyle = '#FFFFFF';
  ctx.fillRect(0, 0, w, h);

  const blob = new Blob([new XMLSerializer().serializeToString(exportSvg(svg))], { type: 'image/svg+xml;charset=utf-8' });
  const url  = URL.createObjectURL(blob);
  const img  = new Image();
  const name = `${presetId || 'wordcloud'}-${viewMode}`;

  img.onload = () => {
    ctx.drawImage(img, 0, 0, w, h);
    URL.revokeObjectURL(url);
    const a = document.createElement('a');
    a.download = `${name}.png`;
    a.href = canvas.toDataURL('image/png');
    a.click();
  };

  img.onerror = () => {
    URL.revokeObjectURL(url);
    const a = document.createElement('a');
    a.download = `${name}.svg`;
    a.href = URL.createObjectURL(blob);
    a.click();
  };

  img.src = url;
}

function handleFile(file) {
  if (!file) return;

  const ext = file.name.slice(file.name.lastIndexOf('.')).toLowerCase();
  if (!['.txt', '.csv'].includes(ext)) {
    say(problem, `"${file.name}" is not a .txt or .csv file. Save it as one of those and try again.`, 'bad');
    return;
  }

  const reader = new FileReader();
  reader.onload = e => {
    textInput.value = e.target.result;
    fileName.textContent = file.name;
    useCustom();
    hide(problem);
    refresh();
  };
  reader.onerror = () => say(problem, `Could not read "${file.name}". Try choosing it again.`, 'bad');
  reader.readAsText(file);
}

/* ══ ADD A TERM ════════════════════════════════════════════════ */

function handleAddApply() {
  const text = addInput.value.trim();
  const parsed = parseTerms(text);

  if (!parsed.length) {
    say(addNote, 'Type at least one term, one per line.', 'warn');
    return;
  }

  const combined = [readStored().trim(), text].filter(Boolean).join('\n');
  const stored = writeStored(combined);

  addInput.value = '';
  refresh();

  const n = parsed.length;
  say(addNote,
    stored
      ? `Added ${n} term${n !== 1 ? 's' : ''}. They are saved in this browser.`
      : `Added ${n} term${n !== 1 ? 's' : ''}, but this browser will not let the page save them, so they go when you reload.`,
    stored ? 'ok' : 'warn');
}

function handleAddCopy() {
  const all = [readStored().trim(), addInput.value.trim()].filter(Boolean).join('\n');

  if (!all) {
    say(addNote, 'There are no added terms to copy yet.', 'warn');
    return;
  }

  const snippet = 'window.WORDCLOUD_MANUAL_TERMS = `\n'
    + all.split('\n').map(l => `  ${l.trim()}`).join('\n')
    + '\n`;';

  navigator.clipboard.writeText(snippet).then(
    () => say(addNote, 'Copied. Paste it over the block in data/manual-terms.js, then commit and push.', 'ok'),
    () => say(addNote, 'This browser blocked the clipboard. Select the terms above and copy them yourself.', 'warn')
  );
}

function handleAddReset() {
  writeStored('');
  addInput.value = '';
  refresh();
  say(addNote, 'Removed the terms you added here. Terms in data/manual-terms.js stay.', 'ok');
}

